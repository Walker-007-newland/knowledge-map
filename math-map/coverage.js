window.runCoverage = function () {
  const L = window.LESSONS;
  const strip = (h) => String(h);
  const texts = {};
  for (const [id, les] of Object.entries(L)) {
    texts[id] = {
      learn: [les.goal, les.fj, ...les.sections.map((s) => s.h + s.html), ...les.pitfalls].map(strip).join(' '),
      ex: les.examples.map((e) => e.q + e.steps.join(' ') + e.ans).join(' '),
      quiz: les.quiz.map((q) => q.q + (q.opts || []).join(' ') + q.why).join(' ')
    };
  }
  const hit = (t, kws) => kws.some((k) => (k instanceof RegExp ? k.test(t) : t.includes(k)));
  return window.CHECKLIST.map(([d, name, kws]) => {
    const where = { learn: [], ex: [], quiz: [] };
    for (const [id, t] of Object.entries(texts)) for (const part of ['learn', 'ex', 'quiz']) if (hit(t[part], kws)) where[part].push(id);
    return { d, name, learn: where.learn.length, ex: where.ex.length, quiz: where.quiz.length, nodes: [...new Set([...where.learn, ...where.ex, ...where.quiz])].slice(0, 4).join(',') };
  });
};
