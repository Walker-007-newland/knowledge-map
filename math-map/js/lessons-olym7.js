  // ───────── 题目配图：生成内联 SVG 字符串（class="fig"，颜色只用 class，不写颜色值）─────────
  const r1 = (v) => Math.round(v * 10) / 10;
  // 窄图补宽到 240，避免被放大得太大
  const SV = (w, h, b) => (w < 240 ? `<svg class="fig" viewBox="0 0 240 ${r1(h)}"><g transform="translate(${r1((240 - w) / 2)},0)">${b}</g></svg>` : `<svg class="fig" viewBox="0 0 ${r1(w)} ${r1(h)}">${b}</svg>`);
  const LN = (a, b, c) => `<line x1="${r1(a[0])}" y1="${r1(a[1])}" x2="${r1(b[0])}" y2="${r1(b[1])}" class="${c || 'sstrong'}"/>`;
  const PG = (P, c) => `<polygon points="${P.map((p) => r1(p[0]) + ',' + r1(p[1])).join(' ')}" class="${c || 'fnone sstrong'}"/>`;
  const RC = (x, y, w, h, c) => `<rect x="${r1(x)}" y="${r1(y)}" width="${r1(w)}" height="${r1(h)}" class="${c}"/>`;
  const PA = (d, c) => `<path d="${d}" class="${c}"/>`;
  const CI = (x, y, r, c) => `<circle cx="${r1(x)}" cy="${r1(y)}" r="${r1(r)}" class="${c}"/>`;
  const TX = (x, y, s, a) => `<text x="${r1(x)}" y="${r1(y)}" text-anchor="${a || 'middle'}">${s}</text>`;
  const LB = (x, y, s, a) => `<text x="${r1(x)}" y="${r1(y)}" text-anchor="${a || 'middle'}" class="lbl">${s}</text>`;
  const MID = (p, q) => [(p[0] + q[0]) / 2, (p[1] + q[1]) / 2];
  const CEN = (...Q) => [Q.reduce((s, q) => s + q[0], 0) / Q.length, Q.reduce((s, q) => s + q[1], 0) / Q.length];
  const XL = (p1, p2, p3, p4) => {
    const d = (p1[0] - p2[0]) * (p3[1] - p4[1]) - (p1[1] - p2[1]) * (p3[0] - p4[0]);
    const t = ((p1[0] - p3[0]) * (p3[1] - p4[1]) - (p1[1] - p3[1]) * (p3[0] - p4[0])) / d;
    return [p1[0] + t * (p2[0] - p1[0]), p1[1] + t * (p2[1] - p1[1])];
  };
  // 通用几何图：P 点坐标；poly 闭合折线；seg 线段；dash 虚线；fill 填色；lab 字母偏移；txt 文字
  const GEO = (w, h, P, o) => {
    let b = '';
    (o.fill || []).forEach(([s, c]) => { b += PG(s.split('').map((k) => P[k]), c || 'f1s'); });
    (o.dash || []).forEach((s) => { b += LN(P[s[0]], P[s[1]], 'smuted dash'); });
    (o.poly || []).forEach((s) => { b += PG(s.split('').map((k) => P[k])); });
    (o.seg || []).forEach((s) => { b += LN(P[s[0]], P[s[1]]); });
    (o.txt || []).forEach((t) => { b += TX(t[0], t[1], t[2], t[3]); });
    Object.keys(o.lab || {}).forEach((k) => { const d = o.lab[k]; b += LB(P[k][0] + d[0], P[k][1] + d[1], k); });
    return SV(w, h, b);
  };
