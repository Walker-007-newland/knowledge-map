  // 'Fe2(SO4)3' → Fe<sub>2</sub>(SO<sub>4</sub>)<sub>3</sub>；开头的系数（如 2H2O 的 2）保持正常
  const sub = s => s.replace(/([A-Za-z)])(\d+)/g, '$1<sub>$2</sub>');
  const C = s => `<span class="chem">${sub(s)}</span>`;
