  // 酸碱滴加的 pH 曲线（20 mL 碱/酸 + 等浓度的酸/碱，加到 20 mL 恰好完全反应）
  function pHAt(v, up) {
    const d = (20 - v) * 0.1 / (20 + v), kw = 1e-14;     // d：过量 OH⁻ 的浓度（负数表示 H⁺ 过量）
    let ph;
    if (d >= 0) ph = 14 + Math.log10((d + Math.sqrt(d * d + 4 * kw)) / 2);
    else ph = -Math.log10((-d + Math.sqrt(d * d + 4 * kw)) / 2);
    return up ? 14 - ph : ph;
  }
  // up=false：向碱中滴加酸；up=true：向酸中滴加碱。pts: [[体积, '标签'], …]
  function figCurve(up, pts, xlabel, caption) {
    const ax = { x: 50, y: 52, w: 260, h: 140, xmax: 40, ymax: 14, xticks: [10, 20, 30], yticks: [7, 14], ylabel: 'pH', xlabel: 'V/mL' };
    let s = window.SIMS.axes(ax);
    s += F.line(ax.px(0), ax.py(7), ax.px(40), ax.py(7), 'thin dash');
    const curve = [];
    for (let v = 0; v <= 40.001; v += 0.25) curve.push([ax.px(v), ax.py(pHAt(v, up))]);
    s += F.poly(curve, 'hi');
    pts.forEach(([v, t]) => {
      const px = ax.px(v), py = ax.py(pHAt(v, up));
      s += F.dot(px, py, 4) + F.text(px + 10, py - 10, t, { cls: 'it', size: 15 });
    });
    s += F.text(ax.x + ax.w / 2, ax.y + ax.h + 32, xlabel, { size: 12 });
    return F.svg(370, 250, s, caption);
  }

