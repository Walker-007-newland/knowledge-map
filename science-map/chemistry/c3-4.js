  function flask(x, y, h, lv) {
    const nb = y + 20, bot = y + h, W = 40, n = 10;
    const hw = yy => n + (W - n) * (yy - nb) / (bot - nb);
    let s = '', ly = bot;
    if (lv) {
      ly = bot - (bot - nb) * lv;
      s += F.polygon([[x - hw(ly), ly], [x + hw(ly), ly], [x + W, bot], [x - W, bot]], 'water');
    }
    s += F.poly([[x - n, y], [x - n, nb], [x - W, bot], [x + W, bot], [x + n, nb], [x + n, y]], 'ink');
    return { s, ly, bot };
  }
