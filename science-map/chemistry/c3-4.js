  // 沿试管方向取点：管口 (x,y)，方向角 deg；t 沿管轴，s 垂直管轴
  function tubeAt(x, y, deg) {
    const a = deg * Math.PI / 180, ux = Math.cos(a), uy = Math.sin(a);
    return (t, s) => [x + ux * t - uy * s, y + uy * t + ux * s];
  }
