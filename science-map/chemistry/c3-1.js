  // 蜡烛与火焰：candle(x, y) 烛芯底端 (x,y)；layers 标出三层火焰
  function candle(x, y, layers) {
    let s = F.rect(x - 9, y, 18, 66, 'soft', 2) + F.line(x, y, x, y - 8, 'ink');
    s += S1.flame(x, y - 2, 52, 15, 'fill:var(--fig-ray);fill-opacity:.25');
    s += S1.flame(x, y - 2, 36, 10, 'fill:var(--fig-ray);fill-opacity:.35');
    s += S1.flame(x, y - 2, 16, 5, 'fill:var(--fig-water)');
    if (layers) {
      s += F.line(x + 13, y - 34, x + 46, y - 50, 'thin') + F.text(x + 50, y - 50, '外焰', { size: 12, a: 'start' });
      s += F.line(x + 6, y - 22, x + 46, y - 26, 'thin') + F.text(x + 50, y - 26, '内焰', { size: 12, a: 'start' });
      s += F.line(x + 2, y - 8, x + 46, y - 2, 'thin') + F.text(x + 50, y - 2, '焰心', { size: 12, a: 'start' });
    }
    return s;
  }
  // 倒扣的烧杯：杯底在上 (x 中心, yTop)，lime=true 内壁涂澄清石灰水；drops 内壁出现水雾
  function cupDown(x, yTop, lime, drops) {
    let s = F.poly([[x - 32, yTop + 62], [x - 32, yTop], [x + 32, yTop], [x + 32, yTop + 62], [x + 38, yTop + 66]], 'ink');
    if (lime) s += F.rect(x - 32, yTop, 64, 6, 'water') + F.rect(x - 32, yTop, 4, 58, 'water') + F.rect(x + 28, yTop, 4, 58, 'water');
    if (drops) [[-26, 14], [-27, 30], [-25, 46], [26, 20], [27, 38], [-10, 8], [10, 8]].forEach(([dx, dy]) => { s += F.circle(x + dx, yTop + dy, 2, 'thin'); });
    return s;
  }

