    let s = thick(HX, 30, HX, AY - 4) + thick(HX, AY + 4, HX, 210) + F.rect(xs, 30, 6, 180, 'soft');
    s += F.arrow(xo, B[1], xo, A[1], { cls: 'hi' }) + F.text(xo - 14, A[1], 'A', { cls: 'it' }) + F.text(xo - 14, B[1], 'B', { cls: 'it' });
