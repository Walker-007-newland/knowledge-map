  // 水下 A 点发出的光经水面 y=sy 折射后进入 E 点：求入射点的 x。k = sin(空气中的角) / sin(水中的角)
  function solveO(ax, ay, ex, ey, sy, k) {
    let lo = Math.min(ax, ex), hi = Math.max(ax, ex);
    const f = x => Math.sin(Math.atan2(Math.abs(ex - x), sy - ey)) - k * Math.sin(Math.atan2(Math.abs(x - ax), ay - sy));
    for (let n = 0; n < 60; n++) { const m = (lo + hi) / 2; if (f(m) > 0) lo = m; else hi = m; }
    return (lo + hi) / 2;
  }

