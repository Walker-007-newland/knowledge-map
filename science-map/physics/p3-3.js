  // 一条特殊光线。which: par 平行于主光轴 | focus 过焦点（凸）/射向异侧焦点（凹）| center 过光心
  // y：入射点在透镜上的高度（向上为正；center 时是起点 x0 处的高度）；x0 起点、x1 终点
  // o.hideIn 不画入射光线；o.hideOut 不画折射光线（作图题题目用）
  function sRay(kind, which, L, Y, f, y, x0, x1, o) {
    o = o || {};
    const cv = kind === 'convex';
    let A, P = [L, Y - y], E, ext = null;
    if (which === 'par') {
      A = [x0, Y - y];
      E = [x1, cv ? Y - y + y * (x1 - L) / f : Y - y - y * (x1 - L) / f];
      if (!cv) ext = [L - f, Y];
    } else if (which === 'focus') {
      if (cv) A = [x0, Y - y * (x0 - L + f) / f];
      else { A = [x0, Y - y * (L + f - x0) / f]; ext = [L + f, Y]; }
      E = [x1, Y - y];
    } else {
      A = [x0, Y - y]; P = [L, Y]; E = [x1, Y + y * (x1 - L) / (L - x0)];
    }
    let s = '';
    if (!o.hideIn) s += F.ray([A, P]);
    if (!o.hideOut) { s += F.ray([P, E]); if (ext) s += F.ray([P, ext], { dash: true, noArrow: true }); }
    return s;
  }
