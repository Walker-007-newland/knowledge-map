    s += F.text(x0 + w + 14, y0 + h - 12, 't/℃', { cls: 'it', size: 13, a: 'end' }) + F.text(x0 + 4, y0 - 18, 'ρ/(g·cm⁻³)', { cls: 'it', size: 13, a: 'start' });
