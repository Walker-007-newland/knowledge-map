  // o.a / o.b：被测物体左右端对准的刻度（物体画在尺子上方）；o.name 物体上的字
  function ruler(x, y, c0, c1, k, mm, o) {
    o = o || {};
    const w = (c1 - c0) * k;
    let s = F.rect(x - 10, y, w + 40, 34, 'soft', 2);
    const step = mm ? 0.1 : 1, n = Math.round((c1 - c0) / step);
    for (let i = 0; i <= n; i++) {
      const c = c0 + i * step, xx = x + i * step * k;
      const whole = Math.abs(c - Math.round(c)) < 1e-6, half = Math.abs(c * 2 - Math.round(c * 2)) < 1e-6;
      s += F.line(xx, y, xx, y + (whole ? 14 : half ? 10 : 6), 'thin');
      if (whole) s += F.text(xx, y + 24, Math.round(c), { size: 11 });
    }
    s += F.text(x + w + 18, y + 24, 'cm', { size: 11 });
    if (o.a != null) {
      const xa = x + (o.a - c0) * k, xb = x + (o.b - c0) * k;
      s += F.block(xa, y - 28, xb - xa, 28, o.name || '') + F.line(xb, y - 30, xb, y + 3, 'thin dash');
    }
    return s;
  }

