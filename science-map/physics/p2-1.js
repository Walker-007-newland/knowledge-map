  // 水的密度随温度变化（0~10 ℃）。表中是 g/cm³
  const RHO_W = [0.999840, 0.999899, 0.999940, 0.999964, 0.999972, 0.999964, 0.999940, 0.999901, 0.999848, 0.999781, 0.999700];
  function rhoW(t) {   // Catmull-Rom 插值，曲线平滑
    const i = Math.max(0, Math.min(9, Math.floor(t))), f = t - i;
    const p = j => RHO_W[Math.max(0, Math.min(10, j))];
    const p0 = p(i - 1), p1 = p(i), p2 = p(i + 1), p3 = p(i + 2);
    return 0.5 * (2 * p1 + (-p0 + p2) * f + (2 * p0 - 5 * p1 + 4 * p2 - p3) * f * f + (-p0 + 3 * p1 - 3 * p2 + p3) * f * f * f);
  }
