  // nodes: {名称: [cx, cy]}；links: [[被吃者, 吃者]]
  function webFig(nodes, links, caption, w, h) {
    const box = name => { const n = String(name).length; return [n * 7 + 10, 15]; };
    let s = '';
    links.forEach(([a, b]) => {
      const [ax, ay] = nodes[a], [bx, by] = nodes[b], dx = bx - ax, dy = by - ay;
      const cut = (hw, hh) => Math.min(dx ? (hw + 3) / Math.abs(dx) : Infinity, dy ? (hh + 3) / Math.abs(dy) : Infinity);
      const ta = cut(...box(a)), tb = cut(...box(b));
      s += F.arrow(ax + dx * ta, ay + dy * ta, bx - dx * tb, by - dy * tb, { cls: 'ink', size: 8 });
    });
    Object.keys(nodes).forEach(k => {
      const [x, y] = nodes[k], [hw, hh] = box(k);
      s += F.rect(x - hw, y - hh, hw * 2, hh * 2, 'soft', 6) + F.text(x, y, k, { size: 14 });
    });
    return F.svg(w, h, s, caption);
  }
